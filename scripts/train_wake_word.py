r"""Your own wake word ("Okay Ash"), trained on your voice in seconds.

openWakeWord already turns every 80 ms of sound into a compact
"embedding" with a model trained on thousands of hours of speech. A
wake word is just a small classifier on top of the last ~1.3 s of those.
This trains that classifier from:
- you saying the phrase ~40 times (recorded here; ~5 minutes)
- negatives: your near-misses ("okay", "ask", "Ashley"...), room sound,
  your recordings from scripts/stt_accuracy.py if you made them, and
  speech generated by the Windows (and, if installed, Piper) voices

It measures the result on recordings it didn't train on, and saves it
encrypted in Ash's data folder (it's derived from your voice, so it's
treated as personal data: listed in "what data do you have", and erased
by "delete all my data").

  1. Record (a folder of your choice; your recordings stay there):
       .venv\Scripts\python.exe scripts\train_wake_word.py record --out D:\okay-ash
  2. Train, measure, and (if you like the numbers) start using it:
       .venv\Scripts\python.exe scripts\train_wake_word.py train --clips D:\okay-ash
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from clips import SAMPLE_RATE, record_command, write_wav  # noqa: E402

PHRASE = "okay ash"
MANIFEST = "manifest.json"
# How to say it: variety makes the model robust to how you'll really say it.
_DELIVERY = ["normally", "normally", "a bit quieter", "a bit louder", "quickly", "slowly",
             "leaning back from the microphone", "as if from across the room", "as if a little tired",
             "with a rising tone, like a question"]
NEAR_MISSES = ["okay", "Ash", "ask", "okay, I'll ask", "that's it", "cash", "Ashley", "okay Google",
               "hey Jarvis", "okay then", "a splash", "ashtray", "what's up", "okay, that's fine",
               "smash it", "Ashton"]
ROOM_SECONDS = 20


def prompts(phrase: str, count: int) -> list[tuple[str, str, str]]:
    """(file name, label, what to say)."""
    spoken = phrase.capitalize().replace(" ash", " Ash")
    items = [(f"wake_{i:03}.wav", "wake", f'"{spoken}" {_DELIVERY[i % len(_DELIVERY)]}')
             for i in range(1, count + 1)]
    items += [(f"near_{i:03}.wav", "near_miss", f'"{text}"') for i, text in enumerate(NEAR_MISSES, start=1)]
    return items


def _load(folder: Path) -> dict:
    path = folder / MANIFEST
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"phrase": PHRASE, "clips": {}}


def _save(folder: Path, manifest: dict) -> None:
    (folder / MANIFEST).write_text(json.dumps(manifest, indent=2), encoding="utf-8")


def record(folder: Path, count: int) -> None:
    import sounddevice as sd

    folder.mkdir(parents=True, exist_ok=True)
    manifest = _load(folder)
    todo = [p for p in prompts(manifest["phrase"], count) if p[0] not in manifest["clips"]]
    print(f"Recording into {folder}. Say each one when prompted; it stops when you go quiet.")
    print("Enter: record   s: skip   q: stop (run again later to continue)\n")
    for name, label, say in todo:
        choice = input(f"Say {say}  > ").strip().lower()
        if choice == "q":
            break
        if choice == "s":
            continue
        audio = record_command(max_seconds=4.0, silence_ms=600)
        if audio is None:
            print("  Didn't hear anything; skipped (run again later to redo it).")
            continue
        write_wav(folder / name, audio)
        manifest["clips"][name] = label
        _save(folder, manifest)

    if "room.wav" not in manifest["clips"]:
        if input(f"\nLast: {ROOM_SECONDS} seconds of your room as it usually sounds (don't say the wake word; "
                 "a fan, typing or quiet TV is fine). Enter to start, s to skip > ").strip().lower() != "s":
            room = sd.rec(int(ROOM_SECONDS * SAMPLE_RATE), samplerate=SAMPLE_RATE, channels=1, dtype="int16")
            sd.wait()
            write_wav(folder / "room.wav", room[:, 0])
            manifest["clips"]["room.wav"] = "room"
            _save(folder, manifest)
    counts = {label: list(manifest["clips"].values()).count(label) for label in ("wake", "near_miss", "room")}
    print(f"\nRecorded: {counts}. Next: train --clips {folder}")


def train(folder: Path, accuracy_clips: Path | None, use: bool | None, threshold: float | None) -> None:
    from ash.audio.personal_wake_word import save_model
    from ash.audio.wake_training import THRESHOLD, train_and_evaluate

    report = train_and_evaluate(folder, accuracy_clips=accuracy_clips, threshold=threshold or THRESHOLD, log=print)
    print("\n" + report.summary())
    if not report.good_enough:
        print("\nNot good enough to use yet, so it wasn't saved. Record more (run record again) and retrain.")
        return
    if use is None:
        use = input("\nSave it and start using it (wake_word.keyword becomes "
                    f"{report.keyword!r}; 'hey_jarvis' stays available)? [Y/n] ").strip().lower() != "n"
    if use:
        from ash.config import save_settings

        save_model(report.model)
        save_settings({"wake_word.keyword": report.keyword})
        print("Saved, encrypted, in Ash's data folder. Restart Ash to use it.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    rec = commands.add_parser("record", help="record yourself saying the wake word, and some near-misses")
    rec.add_argument("--out", type=Path, required=True, help="a folder of your choice (not Ash's data folder)")
    rec.add_argument("--count", type=int, default=40)
    tr = commands.add_parser("train", help="train, measure and save your wake word")
    tr.add_argument("--clips", type=Path, required=True)
    tr.add_argument("--accuracy-clips", type=Path,
                    help="your scripts/stt_accuracy.py recordings, used as extra 'not the wake word' speech")
    tr.add_argument("--threshold", type=float,
                    help="instead of the default (0.9); picking it after seeing the results makes them optimistic")
    tr.add_argument("--use", action=argparse.BooleanOptionalAction, default=None,
                    help="switch Ash to it without asking (or --no-use to only save it)")
    args = parser.parse_args()
    if args.command == "record":
        record(args.out, args.count)
    else:
        train(args.clips, args.accuracy_clips, args.use, args.threshold)


if __name__ == "__main__":
    main()
